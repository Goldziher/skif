// Renders ../docs/rules.md into one page per rule category under src/content/docs/rules/.
// The output is generated at build time and ignored by git; ../docs/rules.md stays the single source of truth.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "..", "docs", "rules.md");
const outDir = join(root, "src", "content", "docs", "rules");

const categories = {
  manifest: {
    title: "Manifest rules",
    summary: "Hygiene of the root and member `package.json` files: field placement, ordering and toolchain declarations.",
  },
  workspace: {
    title: "Workspace rules",
    summary: "Checks on the workspace layout: patterns that match nothing and directories without a manifest.",
  },
  policy: {
    title: "Policy rules",
    summary:
      "Version groups, semver groups, dependency families and the workspace protocol. Configured with `[policy]`, `[[version-groups]]`, `[[semver-groups]]`, `[workspace-protocol]` and `[[dependency-families]]`.",
  },
  catalog: {
    title: "Catalog rules",
    summary: "pnpm, yarn and bun catalogs: keep catalog entries, `catalog:` references and declared versions consistent. Configured with `[catalog]`.",
  },
  js: {
    title: "JavaScript analysis rules",
    summary:
      "Static analysis of JavaScript and TypeScript sources: unused, unlisted and unresolved dependencies, unused files and exports. These rules need the JS analysis, which `--no-js` or `[js] enabled = false` turns off. Configured with `[js]`.",
  },
};

const lines = readFileSync(source, "utf8").split("\n");

const rules = [];
let current = null;
for (const line of lines) {
  const heading = /^## (\S+)\s*$/.exec(line);
  if (heading) {
    current = { id: heading[1], body: [] };
    rules.push(current);
  } else if (current) {
    current.body.push(line);
  }
}

const parsed = [];
for (const rule of rules) {
  const text = rule.body.join("\n").trim();
  const category = /^- Category: (\S+)$/m.exec(text)?.[1];
  if (!category) continue;
  if (!(category in categories)) throw new Error(`rule ${rule.id} has unknown category ${category}`);
  const description = text.split("\n\n")[0].trim();
  const field = (name) => new RegExp(`^- ${name}: (.+)$`, "m").exec(text)?.[1] ?? "";
  parsed.push({
    id: rule.id,
    category,
    description,
    severity: field("Default severity"),
    fixable: field("Fixable"),
    sherif: /^- sherif name: `(.+)`$/m.exec(text)?.[1],
  });
}

if (parsed.length === 0) throw new Error(`no rules found in ${source}`);

mkdirSync(outDir, { recursive: true });

for (const [category, meta] of Object.entries(categories)) {
  const inCategory = parsed.filter((rule) => rule.category === category);
  if (inCategory.length === 0) throw new Error(`no rules in category ${category}`);
  const out = [
    "---",
    `title: ${meta.title}`,
    `description: ${JSON.stringify(meta.summary.replaceAll("`", ""))}`,
    "---",
    "",
    "{/* Generated by scripts/sync-rules.mjs from docs/rules.md. Do not edit. */}",
    "",
    meta.summary,
    "",
    "| Rule | Default severity | Fixable |",
    "| --- | --- | --- |",
    ...inCategory.map((r) => `| [\`${r.id}\`](#${r.id}) | ${r.severity} | ${r.fixable} |`),
    "",
    "Fixable is `safe` (applied by `--fix`), `unsafe` (applied only by `--fix-unsafe`), `sometimes` (fixable for some findings) or `none`. See the [CLI reference](../../reference/cli/).",
    "",
  ];
  for (const r of inCategory) {
    out.push(`## ${r.id}`, "", r.description, "");
    out.push(`- Default severity: ${r.severity}`, `- Fixable: ${r.fixable}`);
    if (r.sherif) out.push(`- sherif name: \`${r.sherif}\``);
    out.push("");
    out.push("```toml", "[rules]", `${r.id} = "${r.severity === "warning" ? "warn" : r.severity}"`, "```", "");
  }
  writeFileSync(join(outDir, `${category}.mdx`), out.join("\n"));
}

console.log(`sync-rules: ${parsed.length} rules into ${Object.keys(categories).length} pages`);
