//! node-modules-inspector: its unconfig file, or the one a script passes with `--config`, is a config file.

use crate::plugin::{Enabler, Plugin, PluginSpec};

/// The `node-modules-inspector` plugin.
pub struct NodeModulesInspector;

static SPEC: PluginSpec = PluginSpec {
    id: "node-modules-inspector",
    enablers: &[Enabler::Dependency("node-modules-inspector")],
    config: &[
        "node-modules-inspector.config",
        "node-modules-inspector.config.{json,ts,mts,cts,js,mjs,cjs}",
    ],
    binaries: &["node-modules-inspector"],
    ..PluginSpec::DEFAULT
};

impl Plugin for NodeModulesInspector {
    fn spec(&self) -> &'static PluginSpec {
        &SPEC
    }

    fn reads_config(&self) -> bool {
        false
    }
}
