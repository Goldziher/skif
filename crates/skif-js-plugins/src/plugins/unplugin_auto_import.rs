//! unplugin-auto-import: the generated `auto-imports.d.ts` declares the globals the plugin imports, so it is an entry.

use crate::plugin::{Enabler, Plugin, PluginContext, PluginInput, PluginSpec};
use crate::plugins::vue::generated_declarations;

/// The `unplugin-auto-import` plugin.
pub struct UnpluginAutoImport;

static SPEC: PluginSpec = PluginSpec {
    id: "unplugin-auto-import",
    enablers: &[Enabler::Dependency("unplugin-auto-import")],
    ..PluginSpec::DEFAULT
};

impl Plugin for UnpluginAutoImport {
    fn spec(&self) -> &'static PluginSpec {
        &SPEC
    }

    fn reads_config(&self) -> bool {
        false
    }

    fn resolve_workspace(&self, cx: &PluginContext<'_>) -> Vec<PluginInput> {
        generated_declarations(cx, "Generated by unplugin-auto-import")
            .into_iter()
            .map(PluginInput::Entry)
            .collect()
    }
}
