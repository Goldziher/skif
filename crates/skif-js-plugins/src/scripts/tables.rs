#[derive(Clone, Copy)]
pub(super) enum Files {
    /// The first positional argument (after an optional subcommand) is the entry file.
    First,
    /// Every positional argument with a JavaScript or TypeScript extension.
    ScriptExt,
    /// Every positional argument.
    All,
}

/// A tool that runs or tests files given on its command line.
pub(super) struct Runner {
    pub names: &'static [&'static str],
    pub value_flags: &'static [&'static str],
    /// Flags whose value is a module specifier (a dependency or a local file).
    pub dep_flags: &'static [&'static str],
    /// Flags whose value is a file path.
    pub file_flags: &'static [&'static str],
    /// Flags whose value is itself a shell command.
    pub exec_flags: &'static [&'static str],
    pub subcommands: &'static [&'static str],
    pub files: Files,
}

