/// Whether `name` is a command PowerShell runs itself: a cmdlet or function named `Verb-Noun` (`New-Item`,
/// `Get-ChildItem`) or one of its default aliases.
#[must_use]
pub fn is_powershell_command(name: &str) -> bool {
    if POWERSHELL_ALIASES.contains(&name.to_ascii_lowercase().as_str()) {
        return true;
    }
    let capitalized = |part: &str| {
        let mut chars = part.chars();
        chars.next().is_some_and(|c| c.is_ascii_uppercase()) && chars.all(|c| c.is_ascii_alphanumeric())
    };
    name.split_once('-').is_some_and(|(verb, noun)| capitalized(verb) && capitalized(noun))
}

