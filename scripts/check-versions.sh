#!/usr/bin/env bash
# Fails unless every versioned release surface agrees on one version.
#
# Usage: scripts/check-versions.sh [expected-version]
#
# Without an argument the workspace version in Cargo.toml is the reference. Cargo.lock must name it for every
# workspace package, unless SKIP_CARGO_UPDATE=1.
set -euo pipefail

cd "$(dirname "$0")/.."

workspace_version="$(awk '/^\[workspace\.package\]/{p=1;next} /^\[/{p=0} p && /^version *= *"/{gsub(/"/,"",$3);print $3;exit}' Cargo.toml)"
expected="${1:-$workspace_version}"
failures=0

check() {
  local what="$1" actual="$2"
  if [[ "$actual" != "$expected" ]]; then
    echo "::error::${what}: expected ${expected}, found ${actual:-<none>}"
    failures=$((failures + 1))
  fi
}

check "Cargo.toml [workspace.package] version" "$workspace_version"

while IFS= read -r line; do
  file="${line%%:*}"
  pin="$(sed -E 's/.*version *= *"=?([^"]+)".*/\1/' <<<"${line#*:}")"
  name="$(sed -E 's/^ *([A-Za-z0-9_-]+) *=.*/\1/' <<<"${line#*:}")"
  check "${file}: internal dependency ${name}" "$pin"
done < <(grep -HE '^ *skif[A-Za-z0-9_-]* *= *\{.*path *=.*version *= *"' Cargo.toml crates/*/Cargo.toml || true)

# The pin check above reads single-line tables; a pin written any other way would be skipped silently.
while IFS= read -r line; do
  echo "::error::${line%%:*}: internal dependency written as a multi-line table; use one line with path and version"
  failures=$((failures + 1))
done < <(grep -HEn '^\[(dev-|build-)?dependencies\.skif|^ *skif[A-Za-z0-9_-]* *= *\{[^}]*$' Cargo.toml crates/*/Cargo.toml || true)

# Every release build uses --locked, so a Cargo.lock that still names the previous version fails the real tag late.
# SKIP_CARGO_UPDATE=1 (an offline bump, see release-bump.sh) leaves the lock to be refreshed later and skips this check.
if [[ "${SKIP_CARGO_UPDATE:-0}" != "1" ]]; then
  while read -r name lock_version; do
    check "Cargo.lock: ${name}" "$lock_version"
  done < <(awk '
    function flush() { if (name ~ /^skif/ && source == "") print name, version }
    /^\[\[package\]\]/ { flush(); name = ""; version = ""; source = ""; next }
    /^name = "/ { name = $3; gsub(/"/, "", name) }
    /^version = "/ { version = $3; gsub(/"/, "", version) }
    /^source = "/ { source = $3 }
    END { flush() }
  ' Cargo.lock)
fi

check "npm-package/package.json version" "$(jq -r '.version' npm-package/package.json)"

# The agent plugin manifests: Claude Code keeps an installed plugin until its version changes, and the MCP server
# runs the skif-cli release the plugin is published with.
for manifest in .claude-plugin/plugin.json .codex-plugin/plugin.json; do
  check "${manifest} version" "$(jq -r '.version // empty' "$manifest")"
  check "${manifest} MCP server skif-cli version" \
    "$(jq -r '[.mcpServers // {} | .[].args // [] | .[] | select(startswith("skif-cli@")) | ltrimstr("skif-cli@")] | unique | join(",")' "$manifest")"
done

# The per-platform packages and optionalDependencies are generated by `napi create-npm-dirs` / `napi prepublish`
# at publish time; they are not committed, so the committed package must not hand-maintain them.
if [[ "$(jq -r 'has("optionalDependencies")' npm-package/package.json)" == "true" ]]; then
  echo "::error::npm-package/package.json must not declare optionalDependencies; napi generates them"
  failures=$((failures + 1))
fi
if [[ -d npm-package/platforms ]]; then
  echo "::error::npm-package/platforms must not exist; napi generates the platform packages"
  failures=$((failures + 1))
fi

check "poly-hooks.toml pinned skif version" "$(sed -nE 's/.*skif-cli@([0-9][^ "]*).*/\1/p' poly-hooks.toml | sort -u | paste -sd, -)"
check "scripts/pre-commit/run-skif.sh SKIF_VERSION default" "$(sed -nE 's/^SKIF_VERSION="\$\{SKIF_VERSION:-v?([^}]+)\}"$/\1/p' scripts/pre-commit/run-skif.sh)"

# The glibc floor is defined once in scripts/lib/libc.sh; the build matrix cannot source it, so it is cross-checked.
# shellcheck source=lib/libc.sh
source scripts/lib/libc.sh
matrix_floors="$(sed -nE 's/^ *glibc: "([^"]+)".*/\1/p' .github/workflows/publish.yaml | sort -u | paste -sd, -)"
if [[ "$matrix_floors" != "$SKIF_GLIBC_FLOOR" ]]; then
  echo "::error::.github/workflows/publish.yaml glibc matrix value(s) '${matrix_floors:-<none>}' differ from SKIF_GLIBC_FLOOR '${SKIF_GLIBC_FLOOR}' in scripts/lib/libc.sh"
  failures=$((failures + 1))
fi

check "action.yml BAKED_VERSION" "$(sed -nE 's/^ *BAKED_VERSION: "([^"]*)".*/\1/p' action.yml)"

for hooks in .pre-commit-hooks.yaml poly-hooks.toml; do
  if [[ "$(grep -c -- '--no-js' "$hooks")" -ne 2 ]]; then
    echo "::error::${hooks}: both hooks must pass --no-js"
    failures=$((failures + 1))
  fi
  if [[ "$(grep -c -- '--no-install' "$hooks")" -ne 1 ]]; then
    echo "::error::${hooks}: only the fix hook may pass --no-install"
    failures=$((failures + 1))
  fi
  if [[ "$(grep -c -- '--no-prompt' "$hooks")" -ne 1 ]]; then
    echo "::error::${hooks}: only the fix hook may pass --no-prompt (hooks never ask)"
    failures=$((failures + 1))
  fi
done

if [[ "$failures" -gt 0 ]]; then
  echo "${failures} version surface(s) disagree with ${expected}" >&2
  exit 1
fi
echo "All version surfaces agree on ${expected}"
